window.poblarInstituciones = function (selectEl, seleccionado) {
  if (!selectEl) return;
  var esc = function (s) { return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;'); };
  selectEl.innerHTML = window.FRATE_INSTITUCIONES.map(function (n) {
    if (n.indexOf('──') === 0) return '<option disabled>' + esc(n) + '</option>';
    return '<option value="' + esc(n) + '"' + (n === seleccionado ? ' selected' : '') + '>' + esc(n) + '</option>';
  }).join('');
};
